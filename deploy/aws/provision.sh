#!/usr/bin/env bash
# Creates the AWS stack for Gym Social: RDS Postgres, an EC2 instance behind an Elastic IP,
# and the IAM role that lets the instance read its database secret and use the photo bucket.
# Run it in AWS CloudShell. Re-running skips anything that already exists.
#
#   curl -fsSL https://raw.githubusercontent.com/mohamedalsayed12/gym-social-media/main/deploy/aws/provision.sh | bash
set -euo pipefail

export AWS_DEFAULT_REGION=${REGION:-eu-west-2}
NAME=${NAME:-gym-social}
BUCKET=${BUCKET:-gym-social-photos-mk}
REPO=${REPO:-mohamedalsayed12/gym-social-media}
INSTANCE_TYPE=${INSTANCE_TYPE:-t3.micro}
DB_CLASS=${DB_CLASS:-db.t4g.micro}

step() { echo; echo "==> $*"; }
account=$(aws sts get-caller-identity --query Account --output text)
vpc=$(aws ec2 describe-vpcs --filters Name=isDefault,Values=true --query 'Vpcs[0].VpcId' --output text)

step "Security groups"
sg_id() { aws ec2 describe-security-groups --filters "Name=group-name,Values=$1" "Name=vpc-id,Values=$vpc" \
    --query 'SecurityGroups[0].GroupId' --output text; }
web_sg=$(sg_id "$NAME-web")
if [ "$web_sg" = "None" ]; then
    web_sg=$(aws ec2 create-security-group --group-name "$NAME-web" --vpc-id "$vpc" \
        --description "Gym Social web traffic" --query GroupId --output text)
    # Only HTTP and HTTPS are open. Shell access goes through Session Manager, so port 22 stays closed.
    aws ec2 authorize-security-group-ingress --group-id "$web_sg" --ip-permissions \
        'IpProtocol=tcp,FromPort=80,ToPort=80,IpRanges=[{CidrIp=0.0.0.0/0}],Ipv6Ranges=[{CidrIpv6=::/0}]' \
        'IpProtocol=tcp,FromPort=443,ToPort=443,IpRanges=[{CidrIp=0.0.0.0/0}],Ipv6Ranges=[{CidrIpv6=::/0}]' >/dev/null
fi
db_sg=$(sg_id "$NAME-db")
if [ "$db_sg" = "None" ]; then
    db_sg=$(aws ec2 create-security-group --group-name "$NAME-db" --vpc-id "$vpc" \
        --description "Gym Social database, reachable from the web servers only" --query GroupId --output text)
    aws ec2 authorize-security-group-ingress --group-id "$db_sg" --protocol tcp --port 5432 \
        --source-group "$web_sg" >/dev/null
fi
echo "web=$web_sg db=$db_sg"

step "RDS Postgres ($DB_CLASS)"
if ! aws rds describe-db-instances --db-instance-identifier "$NAME-db" >/dev/null 2>&1; then
    # --manage-master-user-password keeps the password in Secrets Manager, generated by AWS.
    # Nobody types it or sees it; the instance reads it at boot through its IAM role.
    aws rds create-db-instance \
        --db-instance-identifier "$NAME-db" \
        --engine postgres --engine-version 16 \
        --db-instance-class "$DB_CLASS" \
        --allocated-storage 20 --storage-type gp3 --storage-encrypted \
        --master-username gymsocial --manage-master-user-password \
        --db-name gymsocial \
        --vpc-security-group-ids "$db_sg" --no-publicly-accessible \
        --backup-retention-period 7 \
        --deletion-protection >/dev/null
    echo "Creating; this usually takes 5-10 minutes"
fi
aws rds wait db-instance-available --db-instance-identifier "$NAME-db"
db_host=$(aws rds describe-db-instances --db-instance-identifier "$NAME-db" \
    --query 'DBInstances[0].Endpoint.Address' --output text)
secret_arn=$(aws rds describe-db-instances --db-instance-identifier "$NAME-db" \
    --query 'DBInstances[0].MasterUserSecret.SecretArn' --output text)
echo "host=$db_host"

step "IAM role for the instance"
role="$NAME-ec2"
if ! aws iam get-role --role-name "$role" >/dev/null 2>&1; then
    aws iam create-role --role-name "$role" --assume-role-policy-document '{
        "Version": "2012-10-17",
        "Statement": [{"Effect": "Allow", "Principal": {"Service": "ec2.amazonaws.com"}, "Action": "sts:AssumeRole"}]
    }' >/dev/null
    aws iam attach-role-policy --role-name "$role" \
        --policy-arn arn:aws:iam::aws:policy/AmazonSSMManagedInstanceCore
    aws iam create-instance-profile --instance-profile-name "$role" >/dev/null
    aws iam add-role-to-instance-profile --instance-profile-name "$role" --role-name "$role"
fi
# The app picks these credentials up automatically through boto3, so no access keys live on the server.
aws iam put-role-policy --role-name "$role" --policy-name "$NAME-app" --policy-document "{
    \"Version\": \"2012-10-17\",
    \"Statement\": [
        {\"Effect\": \"Allow\", \"Action\": [\"s3:PutObject\", \"s3:GetObject\", \"s3:DeleteObject\"],
         \"Resource\": \"arn:aws:s3:::$BUCKET/*\"},
        {\"Effect\": \"Allow\", \"Action\": \"secretsmanager:GetSecretValue\", \"Resource\": \"$secret_arn\"}
    ]
}"

step "EC2 instance ($INSTANCE_TYPE)"
instance=$(aws ec2 describe-instances \
    --filters "Name=tag:Name,Values=$NAME" "Name=instance-state-name,Values=pending,running,stopped" \
    --query 'Reservations[0].Instances[0].InstanceId' --output text)
if [ "$instance" = "None" ]; then
    ami=$(aws ssm get-parameter \
        --name /aws/service/canonical/ubuntu/server/24.04/stable/current/amd64/hvm/ebs-gp3/ami-id \
        --query Parameter.Value --output text)
    user_data=$(mktemp)
    curl -fsSL "https://raw.githubusercontent.com/$REPO/${BRANCH:-main}/deploy/aws/bootstrap.sh" \
        | sed -e "s|__DB_HOST__|$db_host|" -e "s|__SECRET_ARN__|$secret_arn|" \
              -e "s|__BUCKET__|$BUCKET|" -e "s|__REGION__|$AWS_DEFAULT_REGION|" -e "s|__REPO__|$REPO|" \
        > "$user_data"
    sleep 10  # a freshly created instance profile takes a few seconds to become usable
    instance=$(aws ec2 run-instances \
        --image-id "$ami" --instance-type "$INSTANCE_TYPE" \
        --security-group-ids "$web_sg" \
        --iam-instance-profile "Name=$role" \
        --metadata-options HttpTokens=required \
        --block-device-mappings 'DeviceName=/dev/sda1,Ebs={VolumeSize=20,VolumeType=gp3,Encrypted=true}' \
        --user-data "file://$user_data" \
        --tag-specifications "ResourceType=instance,Tags=[{Key=Name,Value=$NAME}]" \
        --query 'Instances[0].InstanceId' --output text)
fi
aws ec2 wait instance-running --instance-ids "$instance"
echo "instance=$instance"

step "Elastic IP"
ip=$(aws ec2 describe-addresses --filters "Name=tag:Name,Values=$NAME" --query 'Addresses[0].PublicIp' --output text)
if [ "$ip" = "None" ]; then
    alloc=$(aws ec2 allocate-address --domain vpc \
        --tag-specifications "ResourceType=elastic-ip,Tags=[{Key=Name,Value=$NAME}]" --query AllocationId --output text)
    aws ec2 associate-address --instance-id "$instance" --allocation-id "$alloc" >/dev/null
    ip=$(aws ec2 describe-addresses --allocation-ids "$alloc" --query 'Addresses[0].PublicIp' --output text)
fi

echo
echo "Done. Account $account, region $AWS_DEFAULT_REGION"
echo "  Instance:  $instance"
echo "  Public IP: $ip"
echo "  Database:  $db_host"
echo "Bootstrap log: aws ssm start-session --target $instance, then: sudo tail -f /var/log/gym-social-bootstrap.log"
